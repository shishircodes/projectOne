// Copies the website's generated palette (src/palette.css, "Himalayan Indigo") into src/theme/palette.ts,
// so the app uses exactly the same light and dark colors. Run after `bun run palette --write` at the repo root:
//   bun run palette        (from apps/mobile)
import path from "node:path";

const root = path.resolve(import.meta.dir, "../../..");
const css = await Bun.file(path.join(root, "src/palette.css")).text();

function block(selector: string) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`No ${selector} block in palette.css`);
  const body = css.slice(start, css.indexOf("}", start));
  const vars: Record<string, string> = {};
  for (const m of body.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)) vars[m[1]] = m[2].trim();
  return vars;
}

const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

function resolve(vars: Record<string, string>) {
  const out: Record<string, string> = {};
  const get = (k: string, depth = 0): string => {
    const v = vars[k];
    if (v === undefined) throw new Error(`Unknown token --${k}`);
    const ref = /^var\(--([a-z0-9-]+)\)$/.exec(v);
    return ref && depth < 10 ? get(ref[1], depth + 1) : v;
  };
  for (const k of Object.keys(vars)) out[camel(k)] = get(k);
  return out;
}

const light = resolve(block(":root"));
// Dark only lists what changes; fall back to the light values for anything it doesn't redefine.
const darkVars = { ...block(":root"), ...block('[data-theme="dark"]') };
const dark = resolve(darkVars);

const fmt = (o: Record<string, string>) =>
  Object.entries(o)
    .map(([k, v]) => `    ${k}: "${v}",`)
    .join("\n");

const out = `// Generated by scripts/palette.ts from src/palette.css ("Himalayan Indigo"). Don't edit by hand.
export const palette = {
  light: {
${fmt(light)}
  },
  dark: {
${fmt(dark)}
  },
} as const;

export type Colors = { [K in keyof typeof palette.light]: string };
`;

await Bun.write(path.join(import.meta.dir, "../src/theme/palette.ts"), out);
console.log(`Wrote src/theme/palette.ts (${Object.keys(light).length} tokens)`);
